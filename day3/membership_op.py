# Membership operator: check if a data exists in a sequential datatype(groupdata, string), Output: Boolean datatype

# in: if data exist output: True otherwise False
# not in: if data exist output: False otherwise True

fruits = ["apple","mango","pineapple","orange","banana"]

print("banana" in fruits)        # True
print("kiwi" in fruits)          # False


print("banana" not in fruits)        # False
print("kiwi" not in fruits)           # True

a = "Mindrises"

print('d' in a)


