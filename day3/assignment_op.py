# Assignment operator: symbols used to assign data to a varaible

# equal to(=)
a = 10
print(a)

# add and assign(+=)
a += 5      # a = a + 5
print(a)

# subtract and assign(-=)
a -= 2      # a = a - 2
print(a)

# multiply and assign(*=)
a *= 2         # a = a * 2
print(a)

