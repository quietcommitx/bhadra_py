# Comperision operator: used to compare the value, Output: Boolean Data

a = 10
b = 1
# equal(==): if values are equal then output: True, otherwise False
print(a == b)

# not equal(!=): if values are equal then output: False, otherwise True
print(a != b)

# greater than(>): if a is greater than b, Output: True, otherwise False
print(a > b)

# less than(<): if a is less than b, Output: True, otherwise False
print(a < b)

# greater than or equal to (>=): if a is greater than or equal to b, Output: True, otherwise False
print(a >= b)

# less than or equal to (<=): if a is less than or equal to b, Output: True, otherwise False
print(a <= b)
